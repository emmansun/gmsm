func generateProductTable(t *testing.T, key []byte, table *[256]byte) {
	t.Helper()
	c, err := newCipherGeneric(key[:])
	if err != nil {
		t.Fatal(err)
	}
	c1 := c.(*sm4Cipher)

	if supportSM4 {
		gcmSm4Init(table, c1.enc[:], INST_SM4)
	} else if supportsAES {
		gcmSm4Init(table, c1.enc[:], INST_AES)
	} else {
		t.Skip("skipping test on unsupported CPU")
	}
}

