func TestGcmSm4Data(t *testing.T) {
	if !(supportsGFMUL) {
		t.Skip("skipping test on unsupported CPU")
	}
	var table [256]byte
	var y [16]byte
	arm64Expected := make([]byte, 16)
	for i, c := range cases {
		clear(table[:])
		key := c.key
		generateProductTable(t, key[:], &table)
		data := c.data
		amd64Expected, _ := hex.DecodeString(c.dataTag)
		copy(arm64Expected, amd64Expected[8:])
		copy(arm64Expected[8:], amd64Expected[:8])
		clear(y[:])
		gcmSm4Data(&table, data, &y)
		switch runtime.GOARCH {
		case "arm64":
			if !bytes.Equal(y[:], arm64Expected) {
				t.Errorf("case %d: unexpected result: got %x, want %x", i, y, arm64Expected)
			}
		case "amd64", "riscv64":
			if !bytes.Equal(y[:], amd64Expected) {
				t.Errorf("case %d: unexpected result: got %x, want %x", i, y, amd64Expected)
			}
		}
	}
}

func TestGcmSm4Finish(t *testing.T) {
	if !(supportsGFMUL) {
		t.Skip("skipping test on unsupported CPU")
	}
	var table [256]byte
	key := [16]byte{0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef, 0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10}
	generateProductTable(t, key[:], &table)

	var y [16]byte
	var tMask [16]byte

	for i, c := range cases {
		data := c.data
		expected, _ := hex.DecodeString(c.expected)
		clear(y[:])
		gcmSm4Data(&table, data, &y)
		dataTag, _ := hex.DecodeString(c.dataTag)
		if !(bytes.Equal(y[:8], dataTag[:8]) || bytes.Equal(y[:8], dataTag[8:])) ||
			!(bytes.Equal(y[8:], dataTag[:8]) || bytes.Equal(y[8:], dataTag[8:])) {
			t.Errorf("case %d: unexpected data tag: got %x, want %x", i, y[:], dataTag)
		}
		gcmSm4Finish(&table, &tMask, &y, 0, uint64(len(data)))
		if !bytes.Equal(y[:], expected) {
			t.Errorf("case %d: unexpected result: got %x, want %x", i, y, expected)
		}
	}
}
