// func simpleBitPack4BitsRVV(dst *byte, f *fieldElement)
TEXT ·simpleBitPack4BitsRVV(SB), NOSPLIT, $0-16
	MOV	dst+0(FP), X10
	MOV	f+8(FP), X11
	MOV	$128, X12 // coefficient pairs remaining

simple_bit_pack4_rvv_loop:
	VSETVLI X12, E32, M1, TA, MA, X13
	VLSEG2E32V (X11), V8
	VSLLVI	$4, V9, V9
	VORVV	V9, V8, V8

	// Narrow one packed 32-bit value per coefficient pair to one byte.
	VSETVLI X13, E16, MF2, TA, MA, X0
	VNSRLWX ZERO, V8, V10
	VSETVLI X13, E8, MF4, TA, MA, X0
	VNSRLWX ZERO, V10, V11
	VSE8V	V11, (X10)

	SLL	$3, X13, X14
	ADD	X14, X11, X11
	ADD	X13, X10, X10
	SUB	X13, X12, X12
	BNEZ	X12, simple_bit_pack4_rvv_loop
	RET

